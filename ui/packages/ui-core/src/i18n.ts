const catalogs: Record<Locale, Record<MessageKey, string>> = { en, vi };

export function resolveLocale(preferred: string | null | undefined): Locale {
  return preferred?.toLowerCase().startsWith("vi") ? "vi" : "en";
}

export function translate(locale: Locale, key: string): string {
  const catalog = catalogs[locale];
  return (catalog as Record<string, string>)[key] ?? (en as Record<string, string>)[key] ?? key;
}

export function catalogKeys(locale: Locale): string[] {
  return Object.keys(catalogs[locale]);
}
