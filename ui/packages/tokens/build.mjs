// Compile DTCG (2025.10) token files to CSS custom properties. Presentation has
// three independent dimensions here: theme (light/dark/high-contrast), density
// (comfortable/compact) and appearance (calm plus any later variant). The base file
// is the light + comfortable + calm set; a dimension file overrides only what it
// changes, and aliases ("{group.token}") are resolved per resulting variant.
//
// Supported $type subset: color (string), dimension/duration ({value,unit}),
// fontFamily (list), number, and shadow as a single {color,offsetX,offsetY,blur,
// spread} layer. Anything else is written verbatim. Output is committed and checked
// in CI (`pnpm gen:check`).
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const here = p => fileURLToPath(new URL(p, import.meta.url));
const THEMES = ["light", "dark", "high-contrast"];
/**
 * Comfortable and calm are the base set, so they contribute no override file.
 *
 * An appearance changes emphasis, shape, scale and motion only. Colour belongs to
 * the theme: an appearance that redefined a colour role would apply on top of every
 * theme and could silently break a contrast guarantee the theme established. The one
 * exception is aliasing one colour role to another already-checked role in the same
 * theme, which the contrast tests still verify per variant.
 */
const DENSITIES = ["comfortable", "compact"];
const APPEARANCES = ["calm", "presence", "operator"];
const load = name => JSON.parse(readFileSync(here(`./tokens/${name}.tokens.json`), "utf8"));
const optional = name => (existsSync(here(`./tokens/${name}.tokens.json`)) ? load(name) : null);

function flatten(group, path = [], inheritedType, out = {}) {
  const type = group.$type ?? inheritedType;
  for (const [key, node] of Object.entries(group)) {
    if (key.startsWith("$")) continue;
    if (node && typeof node === "object" && "$value" in node) {
      out[[...path, key].join(".")] = { type: node.$type ?? type, value: node.$value };
    } else if (node && typeof node === "object") {
      flatten(node, [...path, key], type, out);
    }
  }
  return out;
}

function resolve(tokens, name, seen = new Set()) {
  const token = tokens[name];
  if (!token) throw new Error(`unknown token ${name}`);
  if (typeof token.value === "string" && /^\{[^}]+\}$/.test(token.value)) {
    const ref = token.value.slice(1, -1);
    if (seen.has(ref)) throw new Error(`alias cycle at ${name}`);
    return resolve(tokens, ref, new Set([...seen, name]));
  }
  return token;
}

const length = v => `${v.value}${v.unit}`;

function cssValue({ type, value }) {
  if (type === "dimension" || type === "duration") return length(value);
  if (type === "fontFamily") return value.map(f => (/\s/.test(f) ? `"${f}"` : f)).join(", ");
  if (type === "shadow") {
    const layers = Array.isArray(value) ? value : [value];
    return layers
      .map(l => `${length(l.offsetX)} ${length(l.offsetY)} ${length(l.blur)} ${length(l.spread)} ${l.color}`)
      .join(", ");
  }
  return String(value);
}

const varName = name => `--ea-${name.replaceAll(".", "-")}`;
const base = flatten(load("base"));
const publicNames = tokens => Object.keys(tokens).filter(n => !n.startsWith("palette."));
const resolveAll = tokens =>
  Object.fromEntries(publicNames(tokens).map(n => [n, cssValue(resolve(tokens, n))]));

/** Only the values a dimension actually changes are emitted in its block. */
const changed = (variant, reference) =>
  Object.fromEntries(Object.entries(variant).filter(([n, v]) => reference[n] !== v));

const block = (selector, values) =>
  Object.keys(values).length === 0
    ? ""
    : `${selector} {\n${Object.entries(values)
        .map(([n, v]) => `  ${varName(n)}: ${v};`)
        .join("\n")}\n}\n`;

const resolved = {};
let css = "/* Generated by packages/tokens/build.mjs from DTCG sources. Do not edit. */\n";

for (const theme of THEMES) {
  const tokens = theme === "light" ? base : { ...base, ...flatten(load(theme)) };
  resolved[theme] = resolveAll(tokens);
  const selector =
    theme === "light"
      ? ':root, :host, [data-theme="light"], :host([data-theme="light"])'
      : `[data-theme="${theme}"], :host([data-theme="${theme}"])`;
  css += block(selector, resolved[theme]);
}

// A density or appearance override applies on top of whichever theme is active, so
// its block is emitted once per theme and carries only the values it changes.
for (const dimension of [
  { kind: "density", values: DENSITIES, file: name => `density-${name}` },
  { kind: "appearance", values: APPEARANCES, file: name => `appearance-${name}` },
]) {
  for (const value of dimension.values) {
    const overrides = optional(dimension.file(value));
    if (!overrides) continue;
    for (const theme of THEMES) {
      const themed = theme === "light" ? base : { ...base, ...flatten(load(theme)) };
      const variant = resolveAll({ ...themed, ...flatten(overrides) });
      const delta = changed(variant, resolved[theme]);
      resolved[`${theme}+${value}`] = variant;
      // `:host` only accepts a single parenthesised selector, so the shadow-root
      // form carries both attributes inside one argument.
      const scope = `[data-${dimension.kind}="${value}"]`;
      const selectors =
        theme === "light"
          ? [
              `:root${scope}`,
              `:host(${scope})`,
              `[data-theme="light"]${scope}`,
              `:host([data-theme="light"]${scope})`,
            ]
          : [`[data-theme="${theme}"]${scope}`, `:host([data-theme="${theme}"]${scope})`];
      css += block(selectors.join(", "), delta);
    }
  }
}

writeFileSync(here("./src/generated/tokens.css"), css);
writeFileSync(here("./src/generated/tokens.json"), `${JSON.stringify(resolved, null, 2)}\n`);
