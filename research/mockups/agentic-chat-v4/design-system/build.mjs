import { readFile, writeFile, mkdir } from "node:fs/promises";
const here = p => new URL(p, import.meta.url);
export function flatten(group, path = [], out = {}) {
  for (const [key, node] of Object.entries(group)) {
    if (key.startsWith("$")) continue;
    const name = [...path, key].join(".");
    if ("$value" in node) {
      if (!node.$type) throw Error(`Missing type: ${name}`);
      out[name] = node;
    } else flatten(node, [...path, key], out);
  }
  return out;
}
export function resolve(tokens, name, seen = []) {
  if (seen.includes(name)) throw Error(`Token cycle: ${[...seen, name].join(" → ")}`);
  if (!tokens[name]) throw Error(`Missing token: ${name}`);
  const node = tokens[name];
  if (typeof node.$value === "string" && /^\{.+\}$/.test(node.$value)) {
    const target = resolve(tokens, node.$value.slice(1, -1), [...seen, name]);
    if (target.$type !== node.$type) throw Error(`Alias type mismatch: ${name}`);
    return target;
  }
  return node;
}
const length = (v, units = ["px", "rem"]) => {
  if (!v || !units.includes(v.unit) || !Number.isFinite(v.value)) throw Error("Invalid dimension/duration");
  return `${v.value}${v.unit}`;
};
function color(v) {
  const alpha = v?.alpha ?? 1;
  if (
    !v ||
    v.colorSpace !== "srgb" ||
    !Array.isArray(v.components) ||
    v.components.length !== 3 ||
    [...v.components, alpha].some(c => !Number.isFinite(c) || c < 0 || c > 1)
  )
    throw Error("Only normalized sRGB supported");
  return (
    "#" +
    [...v.components, ...(alpha !== 1 ? [alpha] : [])]
      .map(c =>
        Math.round(c * 255)
          .toString(16)
          .padStart(2, "0"),
      )
      .join("")
  );
}
export function cssValue({ $type: t, $value: v }) {
  switch (t) {
    case "color":
      return color(v);
    case "dimension":
      return length(v);
    case "duration":
      return length(v, ["ms", "s"]);
    case "fontFamily":
      return v.map(f => (/\s/.test(f) ? `"${f}"` : f)).join(", ");
    case "fontWeight":
    case "number":
      return String(v);
    case "shadow":
      return `${length(v.offsetX)} ${length(v.offsetY)} ${length(v.blur)} ${length(v.spread)} ${color(v.color)}`;
    default:
      throw Error(`Unsupported token type: ${t}`);
  }
}
export async function build(check = false) {
  const load = async n => flatten(JSON.parse(await readFile(here(`tokens/${n}.tokens.json`), "utf8")));
  const base = await load("base"),
    resolved = {};
  let css = "/* Generated by design-system/build.mjs. Edit tokens/*.tokens.json. */\n";
  for (const theme of ["light", "dark", "high-contrast"]) {
    const tokens = { ...base, ...(theme === "light" ? {} : await load(theme)) };
    resolved[theme] = Object.fromEntries(
      Object.keys(tokens)
        .filter(k => !k.startsWith("palette."))
        .map(k => [k, cssValue(resolve(tokens, k))]),
    );
    const scope =
      theme === "light"
        ? ':root, :host, [data-theme="light"], :host([data-theme="light"])'
        : `[data-theme="${theme}"], :host([data-theme="${theme}"])`;
    css += `${scope} {\n  color-scheme: ${theme === "dark" ? "dark" : "light"};\n${Object.entries(
      resolved[theme],
    )
      .map(([k, v]) => `  --ea-${k.replaceAll(".", "-")}: ${v};`)
      .join("\n")}\n}\n`;
  }
  const outputs = {
    "generated/metrics.js": `// Generated from tokens; CSS breakpoint literals are checked against these values.\nexport const MOBILE_QUERY = "(max-width: ${resolved.light["layout.mobile-breakpoint"]})";\nexport const ICON_STROKE = ${resolved.light["icon.stroke"]};\n`,
    "generated/tokens.css": css,
    "generated/tokens.json": JSON.stringify(resolved, null, 2) + "\n",
    "generated/token-names.d.ts": `// Generated; use these names for typed customization.\nexport type TokenName = ${Object.keys(
      resolved.light,
    )
      .map(k => JSON.stringify(k))
      .join(" | ")};\n`,
  };
  await mkdir(here("generated/"), { recursive: true });
  for (const [p, s] of Object.entries(outputs)) {
    if (check) {
      if ((await readFile(here(p), "utf8")) !== s) throw Error(`Generated token drift: ${p}`);
    } else await writeFile(here(p), s);
  }
  return resolved;
}
if (process.argv[1] && import.meta.url === new URL(process.argv[1], "file:").href) {
  await build(process.argv.includes("--check"));
  console.log("Tokens: light, dark and high contrast generated/checked.");
}
