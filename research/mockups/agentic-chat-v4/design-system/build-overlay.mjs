import { readFile, writeFile } from "node:fs/promises";
const here = path => new URL(path, import.meta.url);
// Preserve the actual import graph and cascade order of the authored entry.
async function inlineCSS(url, stack = []) {
  if (url.protocol !== "file:" || stack.includes(url.href)) throw Error("Unsupported or circular CSS import");
  const source = await readFile(url, "utf8");
  const imports = [...source.matchAll(/^@import\s+["']([^"']+)["'];\s*$/gm)];
  let output = "",
    offset = 0;
  for (const match of imports) {
    output +=
      source.slice(offset, match.index) + (await inlineCSS(new URL(match[1], url), [...stack, url.href]));
    offset = match.index + match[0].length;
  }
  output += source.slice(offset);
  if (/@import\b/.test(output)) throw Error("Unresolved CSS import");
  return output;
}
const output =
  "/* Generated by build-overlay.mjs; candidate shadow-root evidence only. */\n" +
  ":host { all: initial; display: block; }\n:host([hidden]) { display: none !important; }\n" +
  (await inlineCSS(here("../styles.css"))) +
  "\n" +
  (await readFile(here("overlay.css"), "utf8"));
if (process.argv.includes("--check")) {
  if ((await readFile(here("generated/overlay.css"), "utf8")) !== output)
    throw Error("Overlay CSS build drift");
} else await writeFile(here("generated/overlay.css"), output);
console.log("Candidate Shadow DOM CSS bundled/checked from the authored import graph.");
